class TestEachElementMissingIsRejected:
    @pytest.mark.parametrize("element", EIGHT_ELEMENTS)
    def test_single_element_none_is_rejected(self, element):
        data = valid_kwargs()
        data[element] = None
        assert validate_eight_elements(data) == (element,)

    @pytest.mark.parametrize("element", EIGHT_ELEMENTS)
    def test_rejection_names_the_element(self, element):
        data = valid_kwargs()
        data[element] = None
        with pytest.raises(DelegationRejected) as excinfo:
            require_eight_elements(data)
        err = excinfo.value
        assert element in err.missing
        assert err.code == "E_DELEGATION_INCOMPLETE"
        assert ELEMENT_LABELS[element] in str(err)

    @pytest.mark.parametrize("element", EIGHT_ELEMENTS)
    def test_context_rejects_each_missing_element(self, element):
        data = valid_kwargs()
        data[element] = None
        with pytest.raises(DelegationRejected) as excinfo:
            DelegationContext(**data).require_valid()
        assert element in excinfo.value.missing

    def test_all_eight_missing_reports_all(self):
        ctx = DelegationContext(
            goal=None, constraints=None, prior_artifacts=None, prohibitions=None,
            artifact_format=None, budget_tokens=None, timeout_seconds=None,
            callback_url=None)
        assert ctx.validate() == EIGHT_ELEMENTS

    def test_rejection_to_dict_has_labels_and_reasons(self):
        with pytest.raises(DelegationRejected) as excinfo:
            require_eight_elements(valid_kwargs(goal=None, budget_tokens=0))
        payload = excinfo.value.to_dict()
        assert payload["code"] == "E_DELEGATION_INCOMPLETE"
        assert set(payload["missing"]) == {"goal", "budget_tokens"}
        assert len(payload["missing_labels"]) == 2
        assert payload["reasons"]["budget_tokens"]

    def test_element_problems_order_follows_catalogue(self):
        problems = element_problems(valid_kwargs(timeout_seconds=None, goal=None))
        assert list(problems.keys()) == ["goal", "timeout_seconds"]


