"""TASK-S4-04 委派契约八要素与 task_file 物化 单元测试（§3.9 / §3.10）

覆盖：
- 八要素**缺任一即拒绝**（逐要素单点缺失 + 全缺 + 组合缺），且拒绝原因**点名**缺哪一项
- 「未声明」与「声明为空」的分界（③已有成果 / ④禁止事项空列表合法）
- 质量门：目标过于含糊（< MIN_GOAL_CHARS）、非空约束列表
- task_file 物化格式（八要素平铺 + tenancy/trace/schema_version）与往返一致
- 物化即准入：校验不过**不落盘**（不产生半成品任务文件）
"""

from __future__ import annotations

import json
