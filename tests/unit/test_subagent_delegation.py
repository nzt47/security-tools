class TestTaskFileMaterialisation:
    def test_flat_eight_elements_on_top_level(self):
        payload = build_task_file(make_ctx())
        for name in EIGHT_ELEMENTS:
            assert name in payload, name

    def test_schema_and_identifiers(self):
        ctx = make_ctx(tenant_id="t-9", subject_id="u-7", task_id="task-1",
                       trace_id="trace-1", policy_version="p-3")
        payload = build_task_file(ctx)
        assert payload["schema_version"] == TASK_FILE_SCHEMA_VERSION
        assert payload["delegation_id"] == ctx.delegation_id
        assert payload["delegate_actor"] == ctx.delegate_actor
        assert payload["tenancy"] == {"tenant_id": "t-9", "subject_id": "u-7"}
        assert payload["trace"]["trace_id"] == "trace-1"
        assert payload["trace"]["task_id"] == "task-1"
        assert payload["policy_version"] == "p-3"

    def test_lists_are_json_arrays(self):
        payload = build_task_file(make_ctx(constraints=["a", "b"]))
        assert payload["constraints"] == ["a", "b"]
        assert payload["prior_artifacts"] == ["docs/zh/a.md"]

    def test_build_refuses_invalid_context(self):
        ctx = DelegationContext(**valid_kwargs(callback_url=None))
        with pytest.raises(DelegationRejected):
            build_task_file(ctx)

    def test_write_refuses_invalid_and_leaves_no_file(self, tmp_path):
        """物化即准入：不合格不落盘（不产生半成品任务文件）"""
        target = tmp_path / "sub" / "task_file.json"
        ctx = DelegationContext(**valid_kwargs(goal=None))
        with pytest.raises(DelegationRejected):
            write_task_file(ctx, str(target))
        assert not target.exists()
        assert not target.parent.exists()

    def test_write_creates_parent_dirs_and_valid_json(self, tmp_path):
        target = tmp_path / "a" / "b" / "task_file.json"
        path = write_task_file(make_ctx(), str(target))
        assert os.path.isfile(path)
        with open(path, "r", encoding="utf-8") as fh:
            payload = json.load(fh)
        assert payload["goal"].startswith("把 docs/zh")

    def test_write_is_utf8_chinese_preserved(self, tmp_path):
        path = write_task_file(make_ctx(), str(tmp_path / "tf.json"))
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read()
        assert "把 docs/zh" in text

    def test_roundtrip_preserves_elements(self, tmp_path):
        ctx = make_ctx(constraints=["c1", "c2"], prohibitions=["p1"])
        path = write_task_file(ctx, str(tmp_path / "tf.json"))
        restored = delegation_from_task_file(load_task_file(path))
        assert restored.elements() == ctx.elements()
        assert restored.delegation_id == ctx.delegation_id

    def test_roundtrip_preserves_tenancy_and_trace(self, tmp_path):
        ctx = make_ctx(tenant_id="t-1", subject_id="s-1", task_id="tk",
                       trace_id="tr", parent_trace_id="ptr", policy_version="pv")
        path = write_task_file(ctx, str(tmp_path / "tf.json"))
        restored = delegation_from_task_file(load_task_file(path))
        assert restored.tenant_id == "t-1"
        assert restored.subject_id == "s-1"
        assert restored.trace_id == "tr"
        assert restored.parent_trace_id == "ptr"
        assert restored.policy_version == "pv"

    def test_from_task_file_keeps_missing_elements_as_none(self):
        """缺失要素原样透传（不填默认值），使校验能如实点名"""
        restored = delegation_from_task_file({"goal": "足够长的一个目标描述"})
        assert restored.constraints is None
        assert restored.callback_url is None
        assert "constraints" in restored.validate()

    def test_load_task_file_rejects_non_object(self, tmp_path):
        path = tmp_path / "bad.json"
        path.write_text("[1, 2, 3]", encoding="utf-8")
        from agent.subagent.delegation import DelegationError
        with pytest.raises(DelegationError):
            load_task_file(str(path))

    def test_metadata_passthrough(self):
        payload = build_task_file(make_ctx(metadata={"workspace_id": "ws-1"}))
        assert payload["metadata"] == {"workspace_id": "ws-1"}
