class TestEightElementCatalogue:
    def test_eight_elements_exactly_eight(self):
        assert len(EIGHT_ELEMENTS) == 8

    def test_eight_elements_documented_order(self):
        """顺序即 §3.9 的 ①→⑧"""
        assert EIGHT_ELEMENTS == (
            "goal", "constraints", "prior_artifacts", "prohibitions",
            "artifact_format", "budget_tokens", "timeout_seconds", "callback_url",
        )

    def test_every_element_has_label(self):
        for name in EIGHT_ELEMENTS:
            assert ELEMENT_LABELS.get(name)

    def test_labels_carry_sequence_numbers(self):
        for idx, name in enumerate(EIGHT_ELEMENTS, start=1):
            assert ELEMENT_LABELS[name].startswith(
                "①②③④⑤⑥⑦⑧"[idx - 1])


