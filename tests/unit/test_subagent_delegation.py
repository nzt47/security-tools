from agent.subagent.delegation import (
    EIGHT_ELEMENTS,
    ELEMENT_LABELS,
    MIN_GOAL_CHARS,
    TASK_FILE_SCHEMA_VERSION,
    DelegationContext,
    DelegationRejected,
    build_task_file,
    delegation_from_task_file,
    element_problems,
    load_task_file,
    require_eight_elements,
    validate_eight_elements,
    write_task_file,
)


def valid_kwargs(**overrides) -> dict:
    """一份合法的八要素（逐项可覆盖为非法值）"""
    data = {
        "goal": "把 docs/zh 下的 12 篇设计稿抽取为可复现步骤序列",
        "constraints": ["只读仓库，不得修改任何文件"],
        "prior_artifacts": ["docs/zh/a.md"],
        "prohibitions": ["不得访问网络"],
        "artifact_format": "JSON Lines：每行 {name, steps[]}",
        "budget_tokens": 20000,
        "timeout_seconds": 300,
        "callback_url": "internal://pipeline/stage2",
    }
    data.update(overrides)
    return data


def make_ctx(**overrides) -> DelegationContext:
    return DelegationContext(**valid_kwargs(**overrides))


