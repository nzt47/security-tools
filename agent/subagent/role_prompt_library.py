    """一套「分身身份提示词」方案（面向 `role_text` 的成稿，不是模板片段）。"""

    id: str
    title: str
    scene: str
    body: str

    def to_dict(self) -> Dict[str, Any]:
        return {"id": self.id, "title": self.title, "scene": self.scene,
                "body": self.body, "chars": len(self.body)}


