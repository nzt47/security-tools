def prompt_sets_catalog() -> List[Dict[str, Any]]:
    """按角色词表顺序投影方案库（UI 数据源；角色 id 与标题全部取自 role_templates）"""
    out: List[Dict[str, Any]] = []
    for tid in ROLE_TEMPLATE_IDS:
        sets = ROLE_PROMPT_SETS.get(tid, ())
        out.append({
            "role_id": tid,
            "role_title": ROLE_TEMPLATES[tid].title,
            "role_note": ROLE_TEMPLATES[tid].note,
            "sets": [s.to_dict() for s in sets],
        })
    return out


def validate_library() -> List[str]:
    """方案库自检（测试与巡检共用；返回问题清单，空 = 合规）

    守住四条：① 角色 id 必须在受控词表里且**每个角色都有方案**；② 每个角色至少两套；
    ③ 每套非空、不超 role_text 上限、不含 `{}` 占位符（role_text 不做插值）；
    ④ 同一角色的方案 id 唯一。
    """
    problems: List[str] = []
    unknown = sorted(set(ROLE_PROMPT_SETS) - set(ROLE_TEMPLATE_IDS))
    if unknown:
        problems.append("方案库里有受控词表之外的角色 id: " + ", ".join(unknown))
    missing = [tid for tid in ROLE_TEMPLATE_IDS if not ROLE_PROMPT_SETS.get(tid)]
    if missing:
        problems.append("这些角色还没有身份提示词方案: " + ", ".join(missing))
    for tid, sets in ROLE_PROMPT_SETS.items():
        if len(sets) < 2:
            problems.append(tid + " 的方案少于两套（要求至少两套可选）")
        seen = set()
        for s in sets:
            if s.id in seen:
                problems.append(tid + " 的方案 id 重复: " + s.id)
            seen.add(s.id)
            if not s.body.strip():
                problems.append(s.id + " 的正文为空")
            if len(s.body) > ROLE_TEXT_MAX_CHARS:
                problems.append(s.id + " 超长（" + str(len(s.body)) + " > " + str(ROLE_TEXT_MAX_CHARS) + "）")
            if "{" in s.body or "}" in s.body:
                problems.append(s.id + " 含 {} 占位符（role_text 不做插值）")
    return problems
